/**
 * Minimal dependency-free .xlsx writer (Office Open XML in an uncompressed ZIP).
 * Supports several sheets, text/number cells, a handful of styles, column widths
 * and a frozen header row — enough for estimate reports.
 */

export type XStyle = 'header' | 'money' | 'moneyBold' | 'title' | 'percent' | 'bold' | 'muted' | 'number';
export type XValue = string | number | null;
export type XCell = XValue | { v: XValue; s?: XStyle };
export interface XSheet { name: string; rows: XCell[][]; widths?: number[]; freezeRow?: number }

const STYLE_INDEX: Record<XStyle, number> = { header: 1, money: 2, moneyBold: 3, title: 4, percent: 5, bold: 6, muted: 7, number: 8 };

const esc = (s: string) => s
  .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function colName(i: number): string {
  let s = '';
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

function sheetXml(sheet: XSheet): string {
  const cols = sheet.widths?.length ? `<cols>${sheet.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>` : '';
  const pane = sheet.freezeRow ? `<sheetViews><sheetView workbookViewId="0"><pane ySplit="${sheet.freezeRow}" topLeftCell="A${sheet.freezeRow + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>` : '';
  const rows = sheet.rows.map((row, r) => {
    const cells = row.map((cell, c) => {
      const { v, s } = cell !== null && typeof cell === 'object' ? cell : { v: cell, s: undefined };
      if (v === null || v === undefined || v === '') return s ? `<c r="${colName(c)}${r + 1}" s="${STYLE_INDEX[s]}"/>` : '';
      const ref = `${colName(c)}${r + 1}`;
      const style = s ? ` s="${STYLE_INDEX[s]}"` : '';
      if (typeof v === 'number') return Number.isFinite(v) ? `<c r="${ref}"${style}><v>${v}</v></c>` : '';
      return `<c r="${ref}" t="inlineStr"${style}><is><t xml:space="preserve">${esc(v)}</t></is></c>`;
    }).join('');
    return `<row r="${r + 1}">${cells}</row>`;
  }).join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${pane}${cols}<sheetData>${rows}</sheetData></worksheet>`;
}

